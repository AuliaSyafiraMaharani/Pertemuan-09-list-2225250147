# Nama File : 02_indeks_slicing.py
# Deskripsi : Mengakses elemen list menggunakan indeks positif, negatif, dan slicing.

# Input / Inisialisasi Data
nilai = [75, 80, 65, 90, 88, 70]

# Proses & Output
print("Elemen pertama (indeks 0)   :", nilai[0])
print("Elemen terakhir (indeks -1)  :", nilai[-1])
print("Tiga elemen awal ([:3])      :", nilai[:3])
print("Elemen indeks 1 hingga 3 ([1:4]):", nilai[1:4])